    /**
     * 会员登录
     *
     * @ApiMethod (POST)
     * @ApiParams (name="account", type="string", required=true, description="账号")
     * @ApiParams (name="password", type="string", required=true, description="密码")
     */
    public function login()
    {
        $account = $this->request->post('account');
        $password = $this->request->post('password');
        if (!$account || !$password) {
            $this->error(__('Invalid parameters'));
        }
        $ret = $this->auth->login($account, $password);
        if ($ret) {
            $data = ['userinfo' => $this->auth->getUserinfo()];
            $this->success(__('Logged in successful'), $data);
        } else {
            $this->error($this->auth->getError());
        }
    }
    /**
     * 会员登录与注册
     */
    public function loginregister()
    {
         // $this->success(__('Logged in successful'), "");
       //只要uername就能登录成功
       $username = $this->request->post('openid');
       if($username!=0){
           if (!$username ) {
                $this->error(__('Invalid parameters'));
            }
       }
       
        $ret = $this->auth->loginByUsername($username);
        if ($ret) {
            $userData = $this->auth->getUserinfo();
            //获取等级类型
            $levelTypeModel = new LevelTypeModel();
            $levelTypes = $levelTypeModel->getAll();
            // $levelTypes = $levelTypes->toArray();
            //获取用户的所有通过记录
            $passModel = new PassModel();
            $passes = $passModel->getAll($userData['id']);
            //遍历等级类型，判断是否有符合的
            foreach ($levelTypes as $levelType) {
                  $levelType->type = $levelType->id;
                  //移除id
                  unset($levelType->id);
                  $levelType->index = 0;
                   //判断是否通过了该关卡
                foreach ($passes as $pass) {
                    if ($pass->type == $levelType->type) {
                       $levelType->index = $pass->sortId;
                    }
                }
            }
            $userData['pass'] = $levelTypes;//通关id
            //获取用户的所有特殊装备
            $specialequipmentsModel = new SpecialequipmentsModel();
            $userData['equipmentDetails'] = $specialequipmentsModel->getAll($userData['equipment'],$userData['equipmentEquipped']);//特殊装备详情
            //获取用户的所有升级记录
            $upgradeModel = new UpgradeModel();
            $userData['upgradeDatas'] = $upgradeModel->getAll($userData['upgradeData']);//升级记录详情
            //  $userData['upgradeDatas']=$upgradeModel->getUserUpgradeDatas($userData['upgradeData']);
             $userData['equipmentEquippedIndex']=json_decode($userData['equipmentEquipped'],true);
            // $data = ['userinfo' => $userData];

            $skillModel = new SkillModel();
            $userData['skillDetails'] = $skillModel->getAll($userData['skill']);//技能详情
            

            $this->success(__('Logged in successful'), $userData);
        } else {
            $this->error($this->auth->getError());
        }
    }
    /**
     * 获取微信的openid
     */
    public function WXLogin()
    {
         $code = $this->request->get('code');
        if(empty($code)){
            $this->error('登录凭证不能为空');
        }
        // 调用微信登录接口
        $result = $this->auth->loginByWechat($code);
        if(!$result){
            $this->error($this->auth->getError());
        }
        //在data中添加code
        $result['code'] = 1;
        // 返回登录结果
        $this->success('success',$result);
    }
    
      /**
     * 初始化用户数据
     */
    public function initUserData()
    {
        $username = $this->request->post('openid');
        if($username != 0) {
             if (!$username) {
                $this->error(__('Invalid parameters'));
            }
        }       
       
        $ret = $this->auth->initUserData($username);
        if ($ret) {
            $this->success(__('Init user data successful'));
        } else {
            $this->error($this->auth->getError());
        }
    }
    

    /**
     * 手机验证码登录
     *
     * @ApiMethod (POST)
     * @ApiParams (name="mobile", type="string", required=true, description="手机号")
     * @ApiParams (name="captcha", type="string", required=true, description="验证码")
     */
    public function mobilelogin()
    {
        $mobile = $this->request->post('mobile');
        $captcha = $this->request->post('captcha');
        if (!$mobile || !$captcha) {
            $this->error(__('Invalid parameters'));
        }
        if (!Validate::regex($mobile, "^1\d{10}$")) {
            $this->error(__('Mobile is incorrect'));
        }
        if (!Sms::check($mobile, $captcha, 'mobilelogin')) {
            $this->error(__('Captcha is incorrect'));
        }
        $user = \app\common\model\User::getByMobile($mobile);
        if ($user) {
            if ($user->status != 'normal') {
                $this->error(__('Account is locked'));
            }
            //如果已经有账号则直接登录
            $ret = $this->auth->direct($user->id);
        } else {
            $ret = $this->auth->register($mobile, Random::alnum(), '', $mobile, []);
        }
        if ($ret) {
            Sms::flush($mobile, 'mobilelogin');
            $data = ['userinfo' => $this->auth->getUserinfo()];
            $this->success(__('Logged in successful'), $data);
        } else {
            $this->error($this->auth->getError());
        }
    }

    /**
     * 注册会员
     *
     * @ApiMethod (POST)
     * @ApiParams (name="username", type="string", required=true, description="用户名")
     * @ApiParams (name="password", type="string", required=true, description="密码")
     * @ApiParams (name="email", type="string", required=true, description="邮箱")
     * @ApiParams (name="mobile", type="string", required=true, description="手机号")
     * @ApiParams (name="code", type="string", required=true, description="验证码")
     */
    public function register()
    {
        $username = $this->request->post('username');
        $password = $this->request->post('password');
        $email = $this->request->post('email');
        $mobile = $this->request->post('mobile');
        $code = $this->request->post('code');
        if (!$username || !$password) {
            $this->error(__('Invalid parameters'));
        }
        if ($email && !Validate::is($email, "email")) {
            $this->error(__('Email is incorrect'));
        }
        if ($mobile && !Validate::regex($mobile, "^1\d{10}$")) {
            $this->error(__('Mobile is incorrect'));
        }
        $ret = Sms::check($mobile, $code, 'register');
        if (!$ret) {
            $this->error(__('Captcha is incorrect'));
        }
        $ret = $this->auth->register($username, $password, $email, $mobile, []);
        if ($ret) {
            $data = ['userinfo' => $this->auth->getUserinfo()];
            $this->success(__('Sign up successful'), $data);
        } else {
            $this->error($this->auth->getError());
        }
    }

    /**
     * 退出登录
     * @ApiMethod (POST)
     */
    public function logout()
    {
        if (!$this->request->isPost()) {
            $this->error(__('Invalid parameters'));
        }
        $this->auth->logout();
        $this->success(__('Logout successful'));
    }

    /**
     * 修改会员个人信息
     *
     * @ApiMethod (POST)
     * @ApiParams (name="avatar", type="string", required=true, description="头像地址")
     * @ApiParams (name="username", type="string", required=true, description="用户名")
     * @ApiParams (name="nickname", type="string", required=true, description="昵称")
     * @ApiParams (name="bio", type="string", required=true, description="个人简介")
     */
    public function profile()
    {
        $user = $this->auth->getUser();
        $username = $this->request->post('username');
        $nickname = $this->request->post('nickname');
        $bio = $this->request->post('bio');
        $avatar = $this->request->post('avatar', '', 'trim,strip_tags,htmlspecialchars');
        if ($username) {
            $exists = \app\common\model\User::where('username', $username)->where('id', '<>', $this->auth->id)->find();
            if ($exists) {
                $this->error(__('Username already exists'));
            }
            $user->username = $username;
        }
        if ($nickname) {
            $exists = \app\common\model\User::where('nickname', $nickname)->where('id', '<>', $this->auth->id)->find();
            if ($exists) {
                $this->error(__('Nickname already exists'));
            }
            $user->nickname = $nickname;
        }
        $user->bio = $bio;
        $user->avatar = $avatar;
        $user->save();
        $this->success();
    }

    /**
     * 修改邮箱
     *
     * @ApiMethod (POST)
     * @ApiParams (name="email", type="string", required=true, description="邮箱")
     * @ApiParams (name="captcha", type="string", required=true, description="验证码")
     */
    public function changeemail()
    {
        $user = $this->auth->getUser();
        $email = $this->request->post('email');
        $captcha = $this->request->post('captcha');
        if (!$email || !$captcha) {
            $this->error(__('Invalid parameters'));
        }
        if (!Validate::is($email, "email")) {
            $this->error(__('Email is incorrect'));
        }
        if (\app\common\model\User::where('email', $email)->where('id', '<>', $user->id)->find()) {
            $this->error(__('Email already exists'));
        }
        $result = Ems::check($email, $captcha, 'changeemail');
        if (!$result) {
            $this->error(__('Captcha is incorrect'));
        }
        $verification = $user->verification;
        $verification->email = 1;
        $user->verification = $verification;
        $user->email = $email;
        $user->save();

        Ems::flush($email, 'changeemail');
        $this->success();
    }

